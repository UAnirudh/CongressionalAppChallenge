export type Exercise = {
  id: string;
  subject: 'Physics' | 'Math';
  topic: string;
  title: string;
  difficulty: 'Warm-up' | 'Practice' | 'Stretch';
  time: string;
  question: string;
  equation: string;
  focus: string;
  explanation: string[];
  hints: [string, string, string];
  solution: string[];
  answer: number;
  answerUnit: string;
  answerLabel: string;
} & ({ model: Problem; graph?: never } | { model?: never; graph: ExerciseGraph });

function curveGraph(
  name: string,
  xMin: number,
  xMax: number,
  value: (x: number) => number,
  xLabel: string,
  yLabel: string,
  caption: string,
): ExerciseGraph {
  return {
    series: [
      {
        name,
        points: Array.from({ length: 61 }, (_, index) => {
          const x = xMin + ((xMax - xMin) * index) / 60;
          return { x, y: value(x) };
        }),
      },
    ],
    xLabel,
    yLabel,
    description: `${name}. Horizontal axis: ${xLabel}. Vertical axis: ${yLabel}. ${caption}`,
    caption,
  };
}

